//! QNAP QPKG package format.
//!
//! A `.qpkg` file is a self-extracting `/bin/sh` script: the script header is
//! followed by an uncompressed tar archive holding `control.tar.gz` (which
//! contains `qpkg.cfg`, `package_routines`, `install.sh` and the App Center
//! icons), followed by `data.tar.gz`, the payload that gets extracted into
//! `<install volume>/.qpkg/<name>`.
//!
//! QTS sets `QINSTALL_PATH` to the `.qpkg` directory of the selected volume when
//! installing through App Center; when it is unset the header falls back to the
//! volume holding the `Public` share, mirroring what QNAP's own `qbuild`-generated
//! packages do.

use std::{
    fs::{self, File},
    io::{self, Write},
    os::unix::fs::PermissionsExt,
    path::{Path, PathBuf},
};

use flate2::{write::GzEncoder, Compression};

use crate::{config::Config, package::Context, util, Error};

const INSTALL_SCRIPT: &str = include_str!("install.sh");

const DEFAULT_PACKAGE_ROUTINES: &str = r#"#!/bin/sh
# Generated by cargo-packager.
# Called by the installer when the package is removed.
pkg_pre_remove() {
    if [ -n "$QPKG_SERVICE_PROGRAM" ] && [ -x "/etc/init.d/$QPKG_NAME.sh" ]; then
        "/etc/init.d/$QPKG_NAME.sh" stop >/dev/null 2>&1
        /bin/rm -f "/etc/init.d/$QPKG_NAME.sh"
    fi
}
"#;

const HEADER_TEMPLATE: &str = r#"#!/bin/sh
# Generated by cargo-packager: QNAP QPKG self-extracting installer.
QPKG_NAME="__QPKG_NAME__"
QPKG_VER="__QPKG_VER__"

find_base() {
    if [ -n "$QINSTALL_PATH" ] && [ -d "$QINSTALL_PATH" ]; then
        QPKG_ROOT="$QINSTALL_PATH"
        QPKG_DIR="$QINSTALL_PATH/$QPKG_NAME"
        return 0
    fi
    _public=$(/sbin/getcfg Public path -f /etc/config/smb.conf 2>/dev/null)
    if [ -n "$_public" ] && [ -d "$_public" ]; then
        QPKG_ROOT="$(dirname "$_public")/.qpkg"
        QPKG_DIR="$QPKG_ROOT/$QPKG_NAME"
        return 0
    fi
    if [ -d /mnt/HDA_ROOT/update_pkg ]; then
        QPKG_ROOT=/mnt/HDA_ROOT/update_pkg
        QPKG_DIR="$QPKG_ROOT/$QPKG_NAME"
        return 0
    fi
    echo "Failed to install $QPKG_NAME $QPKG_VER: no QPKG installation volume found." >&2
    return 1
}

arch_ok() {
    [ "$(/bin/uname -m)" = "__ARCH__" ]
}

if ! arch_ok; then
    echo "Failed to install $QPKG_NAME $QPKG_VER: this package requires __ARCH__, found $(/bin/uname -m)." >&2
    exit 1
fi

find_base || exit 1

_EXTRACT_DIR="${TMPDIR:-/tmp}/qpkg-$QPKG_NAME-$$"
/bin/rm -rf "$_EXTRACT_DIR"
/bin/mkdir -p "$_EXTRACT_DIR" || exit 1

script_len=__SCRIPT_LEN__
/bin/dd if="${0}" bs=$script_len skip=1 2>/dev/null | /bin/tar -xO | /bin/tar -xz -C "$_EXTRACT_DIR" || {
    echo "Failed to extract the package control files." >&2
    /bin/rm -rf "$_EXTRACT_DIR"
    exit 1
}

offset=$((script_len + __CTRL_LEN__))
/bin/dd if="${0}" bs=$offset skip=1 2>/dev/null | /bin/head -c __DATA_LEN__ > "$_EXTRACT_DIR/data.tar.gz" || {
    echo "Failed to extract the package data." >&2
    /bin/rm -rf "$_EXTRACT_DIR"
    exit 1
}

( cd "$_EXTRACT_DIR" && QPKG_ROOT="$QPKG_ROOT" QPKG_DIR="$QPKG_DIR" /bin/sh ./install.sh )
_rc=$?
/bin/rm -rf "$_EXTRACT_DIR"

if [ $_rc -ne 0 ]; then
    echo "Installation of $QPKG_NAME $QPKG_VER failed." >&2
    exit $_rc
fi

echo "Installed $QPKG_NAME $QPKG_VER to $QPKG_DIR."
exit 0
"#;

/// QNAP architecture string and the value `uname -m` reports on such a device.
fn target_arch(config: &Config) -> crate::Result<(String, &'static str)> {
    if let Some(arch) = config.qpkg().and_then(|qpkg| qpkg.arch.clone()) {
        let uname = match arch.as_str() {
            "x86_64" => "x86_64",
            "x86" => "i686",
            "arm_64" => "aarch64",
            "arm-x41" | "arm-x31" => "armv7l",
            "arm-x19" => "armv5tel",
            other => {
                return Err(Error::InvalidQpkgConfig(format!(
                    "unsupported `qpkg.arch` value `{other}`, expected one of x86_64, x86, arm_64, arm-x41, arm-x31, arm-x19"
                )))
            }
        };
        return Ok((arch, uname));
    }

    let (arch, uname) = match config.target_arch()? {
        "x86_64" => ("x86_64", "x86_64"),
        "x86" => ("x86", "i686"),
        "aarch64" => ("arm_64", "aarch64"),
        "arm" => ("arm-x41", "armv7l"),
        other => {
            return Err(Error::InvalidQpkgConfig(format!(
                "no QPKG architecture for target arch `{other}`; set `qpkg.arch` explicitly"
            )))
        }
    };
    Ok((arch.to_string(), uname))
}

const NAME_MAX_LENGTH: usize = 20;
const VERSION_MAX_LENGTH: usize = 10;

fn validate(name: &str, version: &str) -> crate::Result<()> {
    if name.is_empty() || name.len() > NAME_MAX_LENGTH || name.chars().any(char::is_whitespace) {
        return Err(Error::InvalidQpkgConfig(format!(
            "`qpkg.name` must be 1-{NAME_MAX_LENGTH} characters without whitespace, got `{name}`"
        )));
    }
    if version.is_empty()
        || version.len() > VERSION_MAX_LENGTH
        || version.chars().any(char::is_whitespace)
    {
        return Err(Error::InvalidQpkgConfig(format!(
            "`qpkg.version` must be 1-{VERSION_MAX_LENGTH} characters without whitespace, got `{version}`"
        )));
    }
    Ok(())
}

/// Renders the self-extracting header, patching the `script_len` placeholder so
/// that the value matches the final header length exactly (`dd bs=script_len
/// skip=1` must land on the first byte of the control archive).
fn render_header(
    name: &str,
    version: &str,
    uname_m: &str,
    control_len: u64,
    data_len: u64,
) -> String {
    const PLACEHOLDER: &str = "__SCRIPT_LEN__";

    let base = HEADER_TEMPLATE
        .replace("__QPKG_NAME__", name)
        .replace("__QPKG_VER__", version)
        .replace("__ARCH__", uname_m)
        .replace("__CTRL_LEN__", &control_len.to_string())
        .replace("__DATA_LEN__", &data_len.to_string());

    let fixed = base.len() - PLACEHOLDER.len();
    let mut total = fixed + 1;
    loop {
        let candidate = fixed + total.to_string().len();
        if candidate == total {
            break;
        }
        total = candidate;
    }

    let header = base.replace(PLACEHOLDER, &total.to_string());
    debug_assert_eq!(header.len(), total);
    header
}

fn shell_quote(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for c in value.chars() {
        match c {
            '\\' | '"' | '$' | '`' => {
                out.push('\\');
                out.push(c);
            }
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}

fn write_control_files(
    config: &Config,
    control_dir: &Path,
    name: &str,
    version: &str,
) -> crate::Result<()> {
    let qpkg = config.qpkg();
    let display_name = qpkg
        .and_then(|q| q.display_name.clone())
        .unwrap_or_else(|| config.product_name.clone());
    let author = qpkg
        .and_then(|q| q.author.clone())
        .or_else(|| config.authors.as_ref().map(|authors| authors.join(", ")))
        .unwrap_or_default();
    let summary = qpkg
        .and_then(|q| q.summary.clone())
        .or_else(|| config.description.clone())
        .unwrap_or_default();
    let license = qpkg.and_then(|q| q.license.clone()).unwrap_or_default();
    let qts_min_version = qpkg
        .and_then(|q| q.qts_min_version.clone())
        .unwrap_or_else(|| "4.4.1".to_string());
    let volume_select = qpkg.and_then(|q| q.volume_select).unwrap_or(0);
    let service_program = qpkg.and_then(|q| q.service_program.clone());

    let mut cfg = String::new();
    cfg.push_str(&format!("QPKG_NAME={}\n", shell_quote(name)));
    cfg.push_str(&format!("QPKG_VER={}\n", shell_quote(version)));
    cfg.push_str(&format!("QPKG_AUTHOR={}\n", shell_quote(&author)));
    cfg.push_str(&format!(
        "QPKG_DISPLAY_NAME={}\n",
        shell_quote(&display_name)
    ));
    cfg.push_str(&format!("QPKG_SUMMARY={}\n", shell_quote(&summary)));
    cfg.push_str(&format!("QPKG_LICENSE={}\n", shell_quote(&license)));
    cfg.push_str(&format!(
        "QTS_MINI_VERSION={}\n",
        shell_quote(&qts_min_version)
    ));
    cfg.push_str(&format!("QPKG_VOLUME_SELECT={volume_select}\n"));
    if let Some(service_program) = &service_program {
        cfg.push_str(&format!(
            "QPKG_SERVICE_PROGRAM={}\n",
            shell_quote(service_program)
        ));
    }

    let cfg_path = control_dir.join("qpkg.cfg");
    fs::write(&cfg_path, cfg).map_err(|e| Error::IoWithPath(cfg_path.clone(), e))?;

    let routines = match qpkg.and_then(|q| q.package_routines.as_ref()) {
        Some(path) => {
            fs::read_to_string(path).map_err(|e| Error::IoWithPath(path.to_path_buf(), e))?
        }
        None => DEFAULT_PACKAGE_ROUTINES.to_string(),
    };
    let routines_path = control_dir.join("package_routines");
    fs::write(&routines_path, routines).map_err(|e| Error::IoWithPath(routines_path, e))?;

    let install_path = control_dir.join("install.sh");
    fs::write(&install_path, INSTALL_SCRIPT).map_err(|e| Error::IoWithPath(install_path, e))?;

    if let Some(icons_dir) = qpkg.and_then(|q| q.icons_dir.as_ref()) {
        for (from, to) in [
            (format!("{name}.gif"), ".qpkg_icon.gif"),
            (format!("{name}_gray.gif"), ".qpkg_icon_gray.gif"),
            (format!("{name}_80.gif"), ".qpkg_icon_80.gif"),
        ] {
            let src = icons_dir.join(&from);
            if src.is_file() {
                let dest = control_dir.join(to);
                fs::copy(&src, &dest).map_err(|e| Error::CopyFile(src, dest, e))?;
            }
        }
    }

    Ok(())
}

fn copy_path(src: &Path, dest: &Path) -> crate::Result<()> {
    let metadata = fs::metadata(src).map_err(|e| Error::IoWithPath(src.to_path_buf(), e))?;
    if metadata.is_dir() {
        for entry in walkdir::WalkDir::new(src) {
            let entry = entry?;
            let relative = entry.path().strip_prefix(src)?;
            let target = dest.join(relative);
            if entry.file_type().is_dir() {
                fs::create_dir_all(&target).map_err(|e| Error::IoWithPath(target.clone(), e))?;
            } else {
                if let Some(parent) = target.parent() {
                    fs::create_dir_all(parent)
                        .map_err(|e| Error::IoWithPath(parent.to_path_buf(), e))?;
                }
                fs::copy(entry.path(), &target)
                    .map_err(|e| Error::CopyFile(entry.path().to_path_buf(), target, e))?;
            }
        }
    } else {
        if let Some(parent) = dest.parent() {
            fs::create_dir_all(parent).map_err(|e| Error::IoWithPath(parent.to_path_buf(), e))?;
        }
        fs::copy(src, dest)
            .map_err(|e| Error::CopyFile(src.to_path_buf(), dest.to_path_buf(), e))?;
    }
    Ok(())
}

fn write_payload(config: &Config, payload_dir: &Path) -> crate::Result<()> {
    for binary in &config.binaries {
        let src = config.binary_path(binary);
        let file_name = binary.path.file_name().ok_or_else(|| {
            Error::InvalidQpkgConfig(format!("binary path `{src:?}` has no file name"))
        })?;
        let dest = payload_dir.join(file_name);
        fs::copy(&src, &dest).map_err(|e| Error::CopyFile(src.clone(), dest, e))?;
    }

    config.copy_external_binaries(payload_dir)?;

    if let Some(files) = config.qpkg().and_then(|q| q.files.as_ref()) {
        for (src, target) in files {
            let src = Path::new(src);
            let target = Path::new(target);
            let target = target.strip_prefix("/").unwrap_or(target);
            copy_path(src, &payload_dir.join(target))?;
        }
    }

    Ok(())
}

/// Creates a tar archive whose entries are relative to `src_dir` (no leading
/// directory component) — QPKG archives must unpack directly into the target
/// directory, unlike the layouts `util::create_tar_from_dir` produces.
fn create_tar<W: Write>(src_dir: &Path, writer: W) -> crate::Result<W> {
    use std::os::unix::fs::MetadataExt;

    let mut builder = tar::Builder::new(writer);
    builder.follow_symlinks(false);
    for entry in walkdir::WalkDir::new(src_dir) {
        let entry = entry?;
        let path = entry.path();
        if path == src_dir {
            continue;
        }
        let relative = path.strip_prefix(src_dir)?;
        let metadata = fs::metadata(path).map_err(|e| Error::IoWithPath(path.to_path_buf(), e))?;
        let mut header = tar::Header::new_gnu();
        header.set_metadata_in_mode(&metadata, tar::HeaderMode::Deterministic);
        header.set_mtime(metadata.mtime() as u64);
        if entry.file_type().is_dir() {
            builder.append_data(&mut header, relative, io::empty())?;
        } else {
            let mut file =
                File::open(path).map_err(|e| Error::IoWithPath(path.to_path_buf(), e))?;
            builder.append_data(&mut header, relative, &mut file)?;
        }
    }
    builder.into_inner().map_err(Into::into)
}

fn tar_dir_gz(src_dir: &Path, dest: &Path) -> crate::Result<()> {
    let file = util::create_file(dest)?;
    let encoder = GzEncoder::new(file, Compression::best());
    let encoder = create_tar(src_dir, encoder)?;
    encoder.finish()?.flush()?;
    Ok(())
}

fn tar_dir(src_dir: &Path, dest: &Path) -> crate::Result<()> {
    let file = util::create_file(dest)?;
    let mut file = create_tar(src_dir, file)?;
    file.flush()?;
    Ok(())
}

fn append_file(out: &mut impl Write, path: &Path) -> crate::Result<()> {
    let mut file = File::open(path).map_err(|e| Error::IoWithPath(path.to_path_buf(), e))?;
    io::copy(&mut file, out)?;
    Ok(())
}

#[tracing::instrument(level = "trace", skip(ctx))]
pub(crate) fn package(ctx: &Context) -> crate::Result<Vec<PathBuf>> {
    let Context {
        config,
        intermediates_path,
        ..
    } = ctx;

    let name = config
        .qpkg()
        .and_then(|q| q.name.clone())
        .unwrap_or(config.main_binary_name()?);
    let version = config
        .qpkg()
        .and_then(|q| q.version.clone())
        .filter(|version| !version.is_empty())
        .unwrap_or_else(|| config.version.clone());
    let (arch, uname_m) = target_arch(config)?;
    validate(&name, &version)?;

    let work_dir = intermediates_path.join("qpkg");
    util::create_clean_dir(&work_dir)?;

    let payload_dir = work_dir.join("payload");
    util::create_clean_dir(&payload_dir)?;
    write_payload(config, &payload_dir)?;

    let control_dir = work_dir.join("control");
    util::create_clean_dir(&control_dir)?;
    write_control_files(config, &control_dir, &name, &version)?;

    let data_tar_gz = work_dir.join("data.tar.gz");
    tar_dir_gz(&payload_dir, &data_tar_gz)?;

    let control_tar_gz = work_dir.join("control.tar.gz");
    tar_dir_gz(&control_dir, &control_tar_gz)?;

    let outer_dir = work_dir.join("outer");
    util::create_clean_dir(&outer_dir)?;
    let inner = outer_dir.join("control.tar.gz");
    fs::copy(&control_tar_gz, &inner)
        .map_err(|e| Error::CopyFile(control_tar_gz.clone(), inner.clone(), e))?;
    let control_tar = work_dir.join("control.tar");
    tar_dir(&outer_dir, &control_tar)?;

    let control_len = fs::metadata(&control_tar)?.len();
    let data_len = fs::metadata(&data_tar_gz)?.len();
    let header = render_header(&name, &version, uname_m, control_len, data_len);

    fs::create_dir_all(config.out_dir()).map_err(|e| Error::IoWithPath(config.out_dir(), e))?;
    let package_path = config
        .out_dir()
        .join(format!("{name}_{version}_{arch}.qpkg"));

    tracing::info!(
        "Packaging {} ({})",
        package_path
            .file_name()
            .map(|name| name.to_string_lossy().into_owned())
            .unwrap_or_default(),
        package_path.display()
    );

    let mut out = util::create_file(&package_path)?;
    out.write_all(header.as_bytes())?;
    append_file(&mut out, &control_tar)?;
    append_file(&mut out, &data_tar_gz)?;
    out.flush()?;
    drop(out);

    let mut permissions = fs::metadata(&package_path)?.permissions();
    permissions.set_mode(0o755);
    fs::set_permissions(&package_path, permissions)
        .map_err(|e| Error::IoWithPath(package_path.clone(), e))?;

    Ok(vec![package_path])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn header_length_matches_embedded_script_len() {
        for (control_len, data_len) in [(0_u64, 0_u64), (1536, 10_000), (512 * 7 + 3, 1 << 20)] {
            let header = render_header("probe", "1.0.0", "x86_64", control_len, data_len);
            let expected = header
                .lines()
                .find_map(|line| line.strip_prefix("script_len="))
                .expect("script_len is embedded in the header");
            assert_eq!(
                header.len(),
                expected.parse::<usize>().unwrap(),
                "script_len must equal the header byte length, otherwise dd skips the wrong offset"
            );
        }
    }

    #[test]
    fn header_is_self_consistent() {
        let header = render_header("probe", "1.0.0", "aarch64", 4096, 8192);
        assert!(header.starts_with("#!/bin/sh\n"));
        assert!(header.contains("QPKG_NAME=\"probe\""));
        assert!(header.contains("offset=$((script_len + 4096))"));
        assert!(header.contains("head -c 8192"));
        assert!(header.contains("= \"aarch64\""));
    }

    #[test]
    fn rejects_invalid_names_and_versions() {
        assert!(validate("probe", "1.0.0").is_ok());
        assert!(validate("", "1.0.0").is_err());
        assert!(validate("has space", "1.0.0").is_err());
        assert!(validate("a".repeat(21).as_str(), "1.0.0").is_err());
        assert!(validate("probe", "1".repeat(11).as_str()).is_err());
    }

    #[test]
    fn quotes_shell_values() {
        assert_eq!(shell_quote("plain"), "\"plain\"");
        assert_eq!(shell_quote("a \"b\" $c"), "\"a \\\"b\\\" \\$c\"");
    }

    /// Packages a fake binary, runs the resulting `.qpkg` in a sandbox root and
    /// verifies that the installer lands the payload with the executable bit set.
    /// This is the only check that exercises the `dd` offsets in the header.
    #[cfg(target_os = "linux")]
    #[test]
    fn builds_installable_package() {
        use std::process::Command;

        let tmp_dir = tempfile::tempdir().unwrap();
        let tmp = tmp_dir.path();
        let out_dir = tmp.join("out");
        let bin_dir = tmp.join("bin");
        fs::create_dir_all(&bin_dir).unwrap();
        fs::create_dir_all(&out_dir).unwrap();

        let binary = bin_dir.join("probe");
        fs::write(&binary, "#!/bin/sh\necho probe\n").unwrap();
        fs::set_permissions(&binary, fs::Permissions::from_mode(0o755)).unwrap();

        let config: Config = toml::from_str(&format!(
            r#"
            productName = "Probe"
            version = "1.2.3"
            outDir = "{out}"
            formats = ["qpkg"]
            binaries = [{{ path = "{bin}", main = true }}]

            [qpkg]
            name = "probe"
            displayName = "Probe Tool"
            qtsMinVersion = "4.4.1"
            "#,
            out = out_dir.display(),
            bin = binary.display(),
        ))
        .unwrap();

        let ctx = Context::new(&config).unwrap();
        let packages = package(&ctx).unwrap();
        assert_eq!(packages.len(), 1);

        let qpkg = &packages[0];
        assert_eq!(
            qpkg.file_name().unwrap().to_string_lossy(),
            "probe_1.2.3_x86_64.qpkg"
        );
        let header = fs::read(qpkg).unwrap();
        assert!(header.starts_with(b"#!/bin/sh\n"));
        assert_eq!(
            fs::metadata(qpkg).unwrap().permissions().mode() & 0o777,
            0o755
        );

        // Install into a sandbox volume; QTS sets QINSTALL_PATH the same way.
        let root = tmp.join("volume/.qpkg");
        fs::create_dir_all(&root).unwrap();
        let status = Command::new("/bin/sh")
            .arg(qpkg)
            .env("QINSTALL_PATH", &root)
            .env("TMPDIR", tmp.join("tmp"))
            .status()
            .unwrap();
        assert!(status.success(), "installer exited with {status}");

        let installed = root.join("probe/probe");
        assert!(installed.is_file(), "payload binary not installed");
        assert_eq!(
            fs::read_to_string(&installed).unwrap(),
            "#!/bin/sh\necho probe\n"
        );
        assert_ne!(
            fs::metadata(&installed).unwrap().permissions().mode() & 0o111,
            0,
            "payload binary lost its executable bit"
        );

        // Reinstall over an existing installation (the upgrade path).
        let status = Command::new("/bin/sh")
            .arg(qpkg)
            .env("QINSTALL_PATH", &root)
            .env("TMPDIR", tmp.join("tmp"))
            .status()
            .unwrap();
        assert!(status.success(), "reinstall exited with {status}");
    }
}
